//! Equalizer APO integration (Windows).
//!
//! Equalizer APO re-reads its configuration as soon as a file in its `config` directory
//! changes, so writing `budspulse_eq.txt` atomically gives real-time EQ without glitches.
//! `config.txt` gets a small managed block that includes our file (optionally scoped to the
//! Bluetooth headphones via `Device:`).

use super::{to_apo_text, EqBackendKind, HostEqProfile, HostEqStatus};
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

const OUR_FILE: &str = "budspulse_eq.txt";
const BLOCK_BEGIN: &str = "# >>> BudsPulse (managed block — edit in BudsPulse)";
const BLOCK_END: &str = "# <<< BudsPulse";

pub struct ApoEq {
    config_dir: Option<PathBuf>,
    last_error: Option<String>,
    active: bool,
}

impl ApoEq {
    pub fn new() -> Self {
        ApoEq { config_dir: find_config_dir(), last_error: None, active: false }
    }

    pub fn status(&self) -> HostEqStatus {
        match &self.config_dir {
            None => HostEqStatus {
                backend: EqBackendKind::EqualizerApo,
                available: false,
                active: false,
                message: "Equalizer APO не найден. Установите его (sourceforge.net/projects/equalizerapo) и в Configurator отметьте Bluetooth-наушники.".into(),
                config_path: None,
            },
            Some(dir) => HostEqStatus {
                backend: EqBackendKind::EqualizerApo,
                available: true,
                active: self.active,
                message: match (&self.last_error, self.active) {
                    (Some(e), _) => e.clone(),
                    (None, true) => "применяется в реальном времени (APO должен быть включён для наушников в Configurator)".into(),
                    (None, false) => "готов — включите эквалайзер".into(),
                },
                config_path: Some(dir.join(OUR_FILE).to_string_lossy().into_owned()),
            },
        }
    }

    pub fn apply(&mut self, profile: &HostEqProfile, device_hint: Option<&str>) -> HostEqStatus {
        let Some(dir) = self.config_dir.clone() else { return self.status() };
        let body = render(profile);
        let res = write_atomic(&dir.join(OUR_FILE), body.as_bytes()).and_then(|_| ensure_include(&dir.join("config.txt"), device_hint));
        match res {
            Ok(()) => {
                self.last_error = None;
                self.active = profile.enabled;
            }
            Err(e) => {
                self.active = false;
                self.last_error = Some(if e.kind() == std::io::ErrorKind::PermissionDenied {
                    "нет прав на запись в папку config Equalizer APO — нажмите «Установить» (однократно, с правами администратора)".into()
                } else {
                    format!("ошибка записи конфигурации: {e}")
                });
            }
        }
        self.status()
    }

    /// Grants the local Users group modify rights on the APO config directory (UAC prompt),
    /// then applies the profile.
    pub fn install(&mut self, profile: &HostEqProfile, device_hint: Option<&str>) -> HostEqStatus {
        let Some(dir) = self.config_dir.clone() else { return self.status() };
        let dir_s = dir.to_string_lossy().replace('\'', "''");
        // S-1-5-32-545 = BUILTIN\Users (locale independent)
        let script = format!(
            "Start-Process -FilePath icacls.exe -ArgumentList @('\"{dir_s}\"','/grant','*S-1-5-32-545:(OI)(CI)M','/T') -Verb RunAs -Wait -WindowStyle Hidden"
        );
        let out = std::process::Command::new("powershell.exe")
            .args(["-NoProfile", "-NonInteractive", "-Command", &script])
            .creation_flags_no_window()
            .output();
        if let Err(e) = out {
            self.last_error = Some(format!("не удалось запросить права администратора: {e}"));
            return self.status();
        }
        self.apply(profile, device_hint)
    }

    pub fn shutdown(&mut self) {}
}

impl Default for ApoEq {
    fn default() -> Self {
        Self::new()
    }
}

trait NoWindow {
    fn creation_flags_no_window(&mut self) -> &mut Self;
}

impl NoWindow for std::process::Command {
    fn creation_flags_no_window(&mut self) -> &mut Self {
        use std::os::windows::process::CommandExt;
        const CREATE_NO_WINDOW: u32 = 0x0800_0000;
        self.creation_flags(CREATE_NO_WINDOW)
    }
}

pub fn render(profile: &HostEqProfile) -> String {
    let mut s = String::from("# Generated by BudsPulse — overwritten on every change\n");
    s.push_str(&format!("# Profile: {}\n", profile.name.replace('\n', " ")));
    if profile.enabled {
        let mut p = profile.clone();
        p.bands.retain(|b| b.enabled);
        s.push_str(&to_apo_text(&p));
    } else {
        s.push_str("# (bypassed)\n");
    }
    s
}

fn write_atomic(path: &Path, data: &[u8]) -> std::io::Result<()> {
    let tmp = path.with_extension("txt.tmp");
    {
        let mut f = fs::File::create(&tmp)?;
        f.write_all(data)?;
        f.sync_all()?;
    }
    // std::fs::rename uses MoveFileExW(MOVEFILE_REPLACE_EXISTING) on Windows
    fs::rename(&tmp, path)
}

/// Make sure config.txt contains exactly one managed block including our file.
pub fn ensure_include(config_txt: &Path, device_hint: Option<&str>) -> std::io::Result<()> {
    let existing = fs::read_to_string(config_txt).unwrap_or_default();
    let updated = with_managed_block(&existing, device_hint);
    if updated != existing {
        write_atomic(config_txt, updated.as_bytes())?;
    }
    Ok(())
}

pub fn with_managed_block(existing: &str, device_hint: Option<&str>) -> String {
    // drop any previous managed block
    let mut out = String::new();
    let mut skipping = false;
    for line in existing.lines() {
        if line.trim() == BLOCK_BEGIN {
            skipping = true;
            continue;
        }
        if skipping {
            if line.trim() == BLOCK_END {
                skipping = false;
            }
            continue;
        }
        out.push_str(line);
        out.push('\n');
    }
    let device = device_hint
        .map(|d| d.replace([';', '\n', '\r'], " ").trim().to_string())
        .filter(|d| !d.is_empty())
        .unwrap_or_else(|| "all".into());
    out.push_str(BLOCK_BEGIN);
    out.push('\n');
    out.push_str(&format!("Device: {device}\n"));
    out.push_str(&format!("Include: {OUR_FILE}\n"));
    out.push_str("Device: all\n");
    out.push_str(BLOCK_END);
    out.push('\n');
    out
}

fn find_config_dir() -> Option<PathBuf> {
    if let Some(p) = registry_config_path() {
        if p.is_dir() {
            return Some(p);
        }
    }
    let pf = std::env::var("ProgramFiles").unwrap_or_else(|_| r"C:\Program Files".into());
    let p = PathBuf::from(pf).join("EqualizerAPO").join("config");
    p.is_dir().then_some(p)
}

fn registry_config_path() -> Option<PathBuf> {
    use windows::core::{w, PCWSTR};
    use windows::Win32::System::Registry::{RegGetValueW, HKEY_LOCAL_MACHINE, RRF_RT_REG_SZ};
    let mut buf = vec![0u16; 1024];
    let mut len = (buf.len() * 2) as u32;
    // SAFETY: buffer and length are valid for the duration of the call.
    let r = unsafe {
        RegGetValueW(
            HKEY_LOCAL_MACHINE,
            w!("SOFTWARE\\EqualizerAPO"),
            w!("ConfigPath"),
            RRF_RT_REG_SZ,
            None,
            Some(buf.as_mut_ptr() as *mut _),
            Some(&mut len),
        )
    };
    let _ = PCWSTR::null();
    if r.is_err() {
        return None;
    }
    let n = (len as usize / 2).saturating_sub(1);
    Some(PathBuf::from(String::from_utf16_lossy(&buf[..n])))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn managed_block_is_idempotent() {
        let base = "Preamp: -3 dB\nInclude: example.txt\n";
        let once = with_managed_block(base, Some("Nothing Ear"));
        let twice = with_managed_block(&once, Some("Nothing Ear"));
        assert_eq!(once, twice);
        assert!(once.starts_with(base));
        assert!(once.contains("Device: Nothing Ear\nInclude: budspulse_eq.txt\nDevice: all\n"));
        let other = with_managed_block(&once, None);
        assert_eq!(other.matches(BLOCK_BEGIN).count(), 1);
        assert!(other.contains("Device: all\nInclude: budspulse_eq.txt"));
    }
}
